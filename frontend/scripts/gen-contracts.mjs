// Generates src/core/contracts/error-codes.gen.ts from contracts/error-codes.json.
// CI runs `npm run contracts:check`, which fails if the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../contracts/error-codes.json');
const target = path.resolve(here, '../src/core/contracts/error-codes.gen.ts');

const contract = JSON.parse(readFileSync(source, 'utf8'));
const classes = Object.keys(contract.classes);
const entries = contract.codes
  .map((c) => `  ${c.code}: { http: ${c.http}, class: '${c.class}' },`)
  .join('\n');

const out = `// GENERATED by scripts/gen-contracts.mjs from contracts/error-codes.json — do not edit.
/* eslint-disable */

export const ERROR_CLASSES = ${JSON.stringify(classes)} as const;
export type ErrorClass = (typeof ERROR_CLASSES)[number];

export const ERROR_CODES = {
${entries}
} as const satisfies Record<string, { http: number; class: ErrorClass }>;

export type ErrorCode = keyof typeof ERROR_CODES;

export function isErrorCode(value: unknown): value is ErrorCode {
  return typeof value === 'string' && Object.prototype.hasOwnProperty.call(ERROR_CODES, value);
}
`;
writeFileSync(target, out);
console.warn(`wrote ${path.relative(process.cwd(), target)} (${contract.codes.length} codes)`);
